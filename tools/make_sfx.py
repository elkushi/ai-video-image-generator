"""Build the local sound-effects library procedurally (free, no licences, deterministic).

Writes assets/sfx/<tag>_<n>.wav and assets/sfx/sfx.json, e.g.
  whoosh (scene transitions), pop (list items), tick (counters), impact (hook/reveal),
  riser (build-up before a payoff), chime (end card), click (UI/cursor clicks).
You can also drop CC0 packs (e.g. Kenney "Interface Sounds") into assets/sfx/ and add them to
sfx.json with a tag; build_props.py picks by tag and rotates variants.

Usage:
  python tools/make_sfx.py [--force]
"""
import argparse
import json
import wave
from pathlib import Path

import numpy as np

from common import ROOT

SR = 48000
OUT = ROOT / "assets/sfx"


def env(n: int, attack: float, decay: float) -> np.ndarray:
    t = np.arange(n) / SR
    a = np.minimum(1, t / max(attack, 1e-4))
    return a * np.exp(-np.maximum(0, t - attack) / max(decay, 1e-4))


def lowpass(x: np.ndarray, k: int) -> np.ndarray:
    return np.convolve(x, np.ones(k) / k, mode="same") if k > 1 else x


def whoosh(seconds: float, seed: int, up: bool = True) -> np.ndarray:
    n = int(SR * seconds)
    rng = np.random.default_rng(seed)
    noise = rng.normal(0, 1, n)
    t = np.linspace(0, 1, n)
    out = np.zeros(n)
    # sweep a moving band: blend progressively less-smoothed noise
    for k, w in ((48, 1 - t if up else t), (12, np.sin(np.pi * t)), (3, t if up else 1 - t)):
        out += lowpass(noise, k) * w
    shape = np.sin(np.pi * t) ** 1.6
    return out * shape


def pop(seed: int) -> np.ndarray:
    n = int(SR * 0.12)
    t = np.arange(n) / SR
    f = 520 + 140 * seed
    sweep = f * (1 + 1.5 * np.exp(-t * 60))
    return np.sin(2 * np.pi * np.cumsum(sweep) / SR) * env(n, 0.002, 0.035)


def tick(seed: int) -> np.ndarray:
    n = int(SR * 0.04)
    rng = np.random.default_rng(seed)
    t = np.arange(n) / SR
    return (np.sin(2 * np.pi * (2200 + 300 * seed) * t) * 0.6 + rng.normal(0, 0.4, n)) * env(n, 0.0005, 0.006)


def click(seed: int) -> np.ndarray:
    n = int(SR * 0.05)
    t = np.arange(n) / SR
    return (np.sin(2 * np.pi * 1400 * t) + 0.5 * np.sin(2 * np.pi * 3100 * t)) * env(n, 0.0005, 0.01)


def impact(seed: int) -> np.ndarray:
    n = int(SR * 1.2)
    t = np.arange(n) / SR
    rng = np.random.default_rng(seed)
    boom = np.sin(2 * np.pi * (42 + 70 * np.exp(-t * 18)) * t) * env(n, 0.003, 0.35)
    crack = lowpass(rng.normal(0, 1, n), 4) * env(n, 0.001, 0.05) * 0.5
    return boom + crack


def riser(seconds: float, seed: int) -> np.ndarray:
    n = int(SR * seconds)
    t = np.linspace(0, 1, n)
    rng = np.random.default_rng(seed)
    tone = sum(np.sin(2 * np.pi * np.cumsum(220 * m * (1 + 2.5 * t ** 2)) / SR) / m for m in (1, 2, 3))
    noise = lowpass(rng.normal(0, 1, n), 6) * t ** 2 * 0.6
    return (tone * 0.4 + noise) * t ** 1.5 * np.minimum(1, (1 - t) * 40)


def chime(seed: int) -> np.ndarray:
    n = int(SR * 1.6)
    t = np.arange(n) / SR
    notes = [(784, 0.0), (988, 0.09), (1175, 0.18)] if seed == 0 else [(659, 0.0), (880, 0.1), (1319, 0.2)]
    out = np.zeros(n)
    for f, d in notes:
        s = int(d * SR)
        tt = t[: n - s]
        out[s:] += (np.sin(2 * np.pi * f * tt) + 0.3 * np.sin(2 * np.pi * f * 2.01 * tt)) * np.exp(-tt * 3.2)
    return out


def write(path: Path, x: np.ndarray, peak: float) -> None:
    x = x / (np.abs(x).max() + 1e-9) * peak
    stereo = np.stack([x, np.roll(x, 90)], axis=1)
    with wave.open(str(path), "wb") as wf:
        wf.setnchannels(2)
        wf.setsampwidth(2)
        wf.setframerate(SR)
        wf.writeframes((stereo * 32767).astype(np.int16).tobytes())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    meta_p = OUT / "sfx.json"
    meta = [m for m in (json.loads(meta_p.read_text()) if meta_p.exists() else []) if not m.get("generated")]
    made = {
        "whoosh": [whoosh(0.55, 1), whoosh(0.7, 2, up=False), whoosh(0.45, 3)],
        "pop": [pop(0), pop(1), pop(2)],
        "tick": [tick(0), tick(1)],
        "click": [click(0)],
        "impact": [impact(0)],
        "riser": [riser(1.6, 0)],
        "chime": [chime(0), chime(1)],
    }
    peaks = {"whoosh": 0.5, "pop": 0.45, "tick": 0.35, "click": 0.4, "impact": 0.8, "riser": 0.55, "chime": 0.5}
    for tag, sounds in made.items():
        for i, x in enumerate(sounds):
            f = OUT / f"{tag}_{i + 1}.wav"
            if args.force or not f.exists():
                write(f, x, peaks[tag])
            meta.append({"file": f.name, "tag": tag, "seconds": round(len(x) / SR, 2), "generated": True,
                         "license": "original (generated by tools/make_sfx.py)"})
    meta_p.write_text(json.dumps(meta, indent=2))
    print(f"sfx: {sum(len(v) for v in made.values())} generated in {OUT}")


if __name__ == "__main__":
    main()
